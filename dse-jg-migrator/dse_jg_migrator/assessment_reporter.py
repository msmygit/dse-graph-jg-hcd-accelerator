"""Assessment report renderer — Markdown, JSON, and HTML output."""

from __future__ import annotations

import json
import os
from datetime import UTC, datetime

from dse_jg_migrator.models import AssessmentFinding, AssessmentResult

_SEVERITY_ICON = {"RED": "🔴", "YELLOW": "🟡", "GREEN": "✅"}
_RISK_ICON = {"CRITICAL": "🚨", "HIGH": "🔴", "MEDIUM": "🟡", "LOW": "✅"}


class AssessmentReporter:
    """Renders an AssessmentResult into Markdown, JSON, and HTML files.

    Args:
        result: The AssessmentResult to render.
        output_dir: Directory where output files are written. Created if absent.
    """

    def __init__(self, result: AssessmentResult, output_dir: str = ".") -> None:
        self.result = result
        self.output_dir = output_dir
        os.makedirs(output_dir, exist_ok=True)

    def write_all(self) -> dict[str, str]:
        """Write MD, JSON, and HTML reports.

        Returns:
            dict mapping format names to absolute file paths.
        """
        return {
            "markdown": self._write_markdown(),
            "json": self._write_json(),
            "html": self._write_html(),
        }

    # ──────────────────────────────────────────────────────────────────────────
    # Markdown
    # ──────────────────────────────────────────────────────────────────────────

    def _write_markdown(self) -> str:
        r = self.result
        s = r.summary
        risk_icon = _RISK_ICON.get(r.overall_risk, "🟡")
        reds = s.get("by_severity", {}).get("RED", 0)
        yellows = s.get("by_severity", {}).get("YELLOW", 0)
        greens = s.get("by_severity", {}).get("GREEN", 0)
        total = s.get("total_findings", 0)

        lines: list[str] = [
            "# Pre-Migration Compatibility Assessment Report",
            f"## Graph: {r.graph_name}  ·  Engine: {r.engine}  ·  Assessed: {r.assessed_at}",
            "",
            "---",
            "",
            "## Executive Summary",
            "",
            "| Metric | Value |",
            "|--------|-------|",
            f"| Overall Risk Level | {risk_icon} {r.overall_risk} |",
            f"| Total Findings | {total} |",
            f"| Blockers (RED) | {reds} |",
            f"| Warnings (YELLOW) | {yellows} |",
            f"| Compatible (GREEN) | {greens} |",
            "",
            "### Key Findings",
        ]
        if reds:
            lines.append(f"- 🔴 **{reds} Blocker(s)** require resolution before migration can proceed.")
        if any(f.category == "olap" for f in r.findings if f.severity == "YELLOW"):
            lines.append("- ⚠️  OLAP usage detected — requires separate HadoopGraph/Spark setup.")
        if greens and not reds and not yellows:
            lines.append("- ✅  All checks passed — schema is fully compatible.")

        # Group findings by category
        lines += ["", "---", "", "## Findings by Category", ""]
        by_cat: dict[str, list[AssessmentFinding]] = {}
        for f in r.findings:
            by_cat.setdefault(f.category, []).append(f)

        for cat, cat_findings in sorted(by_cat.items()):
            lines.append(f"### {cat.replace('_', ' ').title()}")
            lines.append("")
            lines.append("| Rule ID | Severity | Title | Detail |")
            lines.append("|---------|----------|-------|--------|")
            for f in cat_findings:
                icon = _SEVERITY_ICON.get(f.severity, "❓")
                detail_short = (f.detail[:80] + "…") if len(f.detail) > 80 else f.detail
                lines.append(f"| {f.rule_id} | {icon} {f.severity} | {f.title} | {detail_short} |")
            lines.append("")

        # Blockers section — only shown when RED findings exist
        red_findings = [f for f in r.findings if f.severity == "RED"]
        if red_findings and r.overall_risk in ("HIGH", "CRITICAL"):
            lines += ["---", "", "## Blockers (must resolve before migration)", ""]
            for i, f in enumerate(red_findings, 1):
                lines.append(f"### {i}. [{f.rule_id}] {f.title}")
                lines.append("")
                lines.append(f"**Detail:** {f.detail}")
                lines.append("")
                lines.append(f"**Remediation:** {f.remediation}")
                lines.append("")
                lines.append(f"**Docs:** <{f.docs_link}>")
                lines.append("")

        lines += [
            "---",
            f"*Report generated by `dse-jg-migrator assess`. "
            f"Source cluster not modified. Generated: {datetime.now(tz=UTC).isoformat().replace('+00:00', 'Z')}*",
        ]

        content = "\n".join(lines)
        path = os.path.join(self.output_dir, f"{self.result.graph_name}-assessment-report.md")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(content)
        return path

    # ──────────────────────────────────────────────────────────────────────────
    # JSON
    # ──────────────────────────────────────────────────────────────────────────

    def _write_json(self) -> str:
        r = self.result
        payload = {
            "schema_version": "1.0",
            "graph_name": r.graph_name,
            "engine": r.engine,
            "assessed_at": r.assessed_at,
            "overall_risk": r.overall_risk,
            "summary": r.summary,
            "cluster_overview": r.cluster_overview,
            "findings": [
                {
                    "rule_id": f.rule_id,
                    "category": f.category,
                    "severity": f.severity,
                    "title": f.title,
                    "detail": f.detail,
                    "remediation": f.remediation,
                    "docs_link": f.docs_link,
                }
                for f in r.findings
            ],
        }
        path = os.path.join(self.output_dir, f"{r.graph_name}-assessment-report.json")
        with open(path, "w", encoding="utf-8") as fh:
            json.dump(payload, fh, indent=2)
        return path

    # ──────────────────────────────────────────────────────────────────────────
    # HTML
    # ──────────────────────────────────────────────────────────────────────────

    def _write_html(self) -> str:
        r = self.result
        risk_icon = _RISK_ICON.get(r.overall_risk, "🟡")
        s = r.summary
        reds = s.get("by_severity", {}).get("RED", 0)
        yellows = s.get("by_severity", {}).get("YELLOW", 0)
        greens = s.get("by_severity", {}).get("GREEN", 0)

        rows = ""
        for f in r.findings:
            icon = _SEVERITY_ICON.get(f.severity, "❓")
            detail_esc = f.detail.replace("<", "&lt;").replace(">", "&gt;")
            rows += (
                f"<tr>"
                f"<td>{f.rule_id}</td>"
                f"<td>{icon} {f.severity}</td>"
                f"<td>{f.category}</td>"
                f"<td>{f.title}</td>"
                f"<td>{detail_esc}</td>"
                f"</tr>\n"
            )

        html = f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Assessment Report: {r.graph_name}</title>
<style>
body {{ font-family: system-ui, sans-serif; max-width: 1100px; margin: 2rem auto; padding: 0 1rem; color: #1f2328; }}
h1 {{ font-size: 1.5rem; border-bottom: 2px solid #e5e7eb; padding-bottom: 0.5rem; }}
h2 {{ font-size: 1.1rem; margin-top: 2rem; color: #57606a; }}
table {{ width: 100%; border-collapse: collapse; font-size: 0.85rem; }}
th {{ background: #f7f8fa; text-align: left; padding: 0.4rem 0.6rem; border: 1px solid #e5e7eb; }}
td {{ padding: 0.35rem 0.6rem; border: 1px solid #e5e7eb; vertical-align: top; }}
.risk-badge {{ display: inline-block; padding: 0.2rem 0.8rem; border-radius: 4px; font-weight: bold; }}
.risk-CRITICAL,.risk-HIGH {{ background: #fee2e2; color: #b91c1c; }}
.risk-MEDIUM {{ background: #fef9c3; color: #92400e; }}
.risk-LOW {{ background: #dcfce7; color: #166534; }}
</style>
</head>
<body>
<h1>Pre-Migration Compatibility Assessment Report</h1>
<p><strong>Graph:</strong> {r.graph_name} &nbsp;|&nbsp;
   <strong>Engine:</strong> {r.engine} &nbsp;|&nbsp;
   <strong>Assessed:</strong> {r.assessed_at}</p>

<h2>Executive Summary</h2>
<table>
<tr><th>Metric</th><th>Value</th></tr>
<tr><td>Overall Risk</td>
<td><span class="risk-badge risk-{r.overall_risk}">{risk_icon} {r.overall_risk}</span></td></tr>
<tr><td>Total Findings</td><td>{len(r.findings)}</td></tr>
<tr><td>Blockers (RED)</td><td>{reds}</td></tr>
<tr><td>Warnings (YELLOW)</td><td>{yellows}</td></tr>
<tr><td>Compatible (GREEN)</td><td>{greens}</td></tr>
</table>

<h2>All Findings</h2>
<table>
<tr><th>Rule ID</th><th>Severity</th><th>Category</th><th>Title</th><th>Detail</th></tr>
{rows}
</table>

<p style="color:#57606a;font-size:0.8rem;margin-top:2rem;border-top:1px solid #e5e7eb;padding-top:0.5rem;">
  Report generated by <code>dse-jg-migrator assess</code>. Source cluster not modified.
</p>
</body>
</html>"""

        path = os.path.join(self.output_dir, f"{r.graph_name}-assessment-report.html")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(html)
        return path
